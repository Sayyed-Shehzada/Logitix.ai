import { UserProfile } from '../types.js';
import { isOwnerAccount, isSuperAdminAccount } from './security.js';

export const WORKSPACE_MEMBER_LIMITS = {
  MAX_CHATS: 20,
  MAX_IMAGES_PER_24H: 7,
  MAX_QUESTIONS_PER_24H: 50,
  WINDOW_MS: 24 * 60 * 60 * 1000, // 24 hours
};

export interface QuotaStatus {
  isPrivileged: boolean;
  roleTier: 'Owner' | 'Super Admin' | 'Admin' | 'Pro Member' | 'Workspace Member';
  speedMode: 'fastest' | 'slow';

  // Chats
  chatsCount: number;
  maxChats: number; // 20 or Infinity
  chatsRemaining: number;
  canCreateChat: boolean;

  // Questions (24h)
  questionsUsed24h: number;
  maxQuestions24h: number; // 50 or Infinity
  questionsRemaining: number;
  canAskQuestion: boolean;
  questionsResetInMs: number;

  // Images (24h)
  imagesUsed24h: number;
  maxImages24h: number; // 7 or Infinity
  imagesRemaining: number;
  canGenerateImage: boolean;
  imagesResetInMs: number;
}

interface StoredUsage {
  questionTimestamps: number[];
  imageTimestamps: number[];
}

const QUOTA_STORAGE_PREFIX = 'logitix_quota_usage_';

function sanitizeEmail(email: string): string {
  return email.trim().toLowerCase().replace(/[^a-z0-9]/g, '_');
}

export function isPrivilegedUser(profile?: Partial<UserProfile> | null): boolean {
  if (!profile || !profile.email) return false;
  const cleanEmail = profile.email.trim().toLowerCase();
  if (isOwnerAccount(cleanEmail)) return true;
  if (isSuperAdminAccount(cleanEmail)) return true;
  if (profile.isAdmin) return true;
  if (profile.role && profile.role.toLowerCase().includes('admin')) return true;
  if (profile.isPro) return true;
  if (profile.plan && profile.plan.toLowerCase().includes('pro')) return true;
  return false;
}

export function getUserRoleTier(profile?: Partial<UserProfile> | null): 'Owner' | 'Super Admin' | 'Admin' | 'Pro Member' | 'Workspace Member' {
  if (!profile || !profile.email) return 'Workspace Member';
  const cleanEmail = profile.email.trim().toLowerCase();
  if (isOwnerAccount(cleanEmail)) return 'Owner';
  if (isSuperAdminAccount(cleanEmail)) return 'Super Admin';
  if (profile.isAdmin || (profile.role && profile.role.toLowerCase().includes('admin'))) return 'Admin';
  if (profile.isPro || (profile.plan && profile.plan.toLowerCase().includes('pro'))) return 'Pro Member';
  return 'Workspace Member';
}

/**
 * Loads stored question and image timestamps for a user from localStorage,
 * automatically pruning timestamps older than 24 hours.
 */
export function getStoredQuotaUsage(email?: string): StoredUsage {
  if (!email) return { questionTimestamps: [], imageTimestamps: [] };
  const cleanEmail = email.trim().toLowerCase();
  const key = `${QUOTA_STORAGE_PREFIX}${sanitizeEmail(cleanEmail)}`;

  try {
    const raw = localStorage.getItem(key);
    const now = Date.now();
    const cutoff = now - WORKSPACE_MEMBER_LIMITS.WINDOW_MS;

    if (raw) {
      const parsed = JSON.parse(raw);
      const qTimestamps = Array.isArray(parsed.questionTimestamps)
        ? parsed.questionTimestamps.filter((t: number) => typeof t === 'number' && t > cutoff)
        : [];
      const imgTimestamps = Array.isArray(parsed.imageTimestamps)
        ? parsed.imageTimestamps.filter((t: number) => typeof t === 'number' && t > cutoff)
        : [];

      // If any expired were pruned, update localStorage
      if (
        (parsed.questionTimestamps && parsed.questionTimestamps.length !== qTimestamps.length) ||
        (parsed.imageTimestamps && parsed.imageTimestamps.length !== imgTimestamps.length)
      ) {
        localStorage.setItem(key, JSON.stringify({ questionTimestamps: qTimestamps, imageTimestamps: imgTimestamps }));
      }

      return { questionTimestamps: qTimestamps, imageTimestamps: imgTimestamps };
    }
  } catch (err) {
    console.warn('Failed to parse stored quota usage:', err);
  }

  return { questionTimestamps: [], imageTimestamps: [] };
}

/**
 * Persists updated usage timestamps into localStorage.
 */
function saveStoredQuotaUsage(email: string, usage: StoredUsage): void {
  const cleanEmail = email.trim().toLowerCase();
  const key = `${QUOTA_STORAGE_PREFIX}${sanitizeEmail(cleanEmail)}`;
  try {
    localStorage.setItem(key, JSON.stringify(usage));
  } catch (err) {
    console.error('Failed to save quota usage to localStorage:', err);
  }
}

/**
 * Records 1 question asked by the user in the 24h rolling window.
 */
export function recordQuestionUsageLocal(email?: string): void {
  if (!email) return;
  const usage = getStoredQuotaUsage(email);
  usage.questionTimestamps.push(Date.now());
  saveStoredQuotaUsage(email, usage);
}

/**
 * Records 1 image generated by the user in the 24h rolling window.
 */
export function recordImageUsageLocal(email?: string): void {
  if (!email) return;
  const usage = getStoredQuotaUsage(email);
  usage.imageTimestamps.push(Date.now());
  saveStoredQuotaUsage(email, usage);
}

/**
 * Computes full real-time QuotaStatus for any user given their profile and conversation count.
 */
export function computeClientQuotaStatus(
  profile?: Partial<UserProfile> | null,
  conversationsCount: number = 0
): QuotaStatus {
  const privileged = isPrivilegedUser(profile);
  const roleTier = getUserRoleTier(profile);
  const email = profile?.email || '';

  if (privileged) {
    return {
      isPrivileged: true,
      roleTier,
      speedMode: 'fastest',
      chatsCount: conversationsCount,
      maxChats: Infinity,
      chatsRemaining: Infinity,
      canCreateChat: true,
      questionsUsed24h: 0,
      maxQuestions24h: Infinity,
      questionsRemaining: Infinity,
      canAskQuestion: true,
      questionsResetInMs: 0,
      imagesUsed24h: 0,
      maxImages24h: Infinity,
      imagesRemaining: Infinity,
      canGenerateImage: true,
      imagesResetInMs: 0,
    };
  }

  // Workspace Member calculations
  const usage = getStoredQuotaUsage(email);
  const now = Date.now();

  // Chats Limit (Max 20)
  const maxChats = WORKSPACE_MEMBER_LIMITS.MAX_CHATS;
  const chatsRemaining = Math.max(0, maxChats - conversationsCount);
  const canCreateChat = conversationsCount < maxChats;

  // Questions Limit (Max 50 in 24h)
  const maxQuestions24h = WORKSPACE_MEMBER_LIMITS.MAX_QUESTIONS_PER_24H;
  const questionsUsed24h = usage.questionTimestamps.length;
  const questionsRemaining = Math.max(0, maxQuestions24h - questionsUsed24h);
  const canAskQuestion = questionsUsed24h < maxQuestions24h;

  let questionsResetInMs = 0;
  if (questionsUsed24h > 0) {
    const oldest = Math.min(...usage.questionTimestamps);
    questionsResetInMs = Math.max(0, oldest + WORKSPACE_MEMBER_LIMITS.WINDOW_MS - now);
  }

  // Images Limit (Max 7 in 24h)
  const maxImages24h = WORKSPACE_MEMBER_LIMITS.MAX_IMAGES_PER_24H;
  const imagesUsed24h = usage.imageTimestamps.length;
  const imagesRemaining = Math.max(0, maxImages24h - imagesUsed24h);
  const canGenerateImage = imagesUsed24h < maxImages24h;

  let imagesResetInMs = 0;
  if (imagesUsed24h > 0) {
    const oldestImg = Math.min(...usage.imageTimestamps);
    imagesResetInMs = Math.max(0, oldestImg + WORKSPACE_MEMBER_LIMITS.WINDOW_MS - now);
  }

  return {
    isPrivileged: false,
    roleTier: 'Workspace Member',
    speedMode: 'fastest',
    chatsCount: conversationsCount,
    maxChats,
    chatsRemaining,
    canCreateChat,
    questionsUsed24h,
    maxQuestions24h,
    questionsRemaining,
    canAskQuestion,
    questionsResetInMs,
    imagesUsed24h,
    maxImages24h,
    imagesRemaining,
    canGenerateImage,
    imagesResetInMs,
  };
}

/**
 * Formats a millisecond duration into human-readable hours and minutes (e.g., "23h 40m" or "14m" or "45s")
 */
export function formatResetTime(ms: number): string {
  if (ms <= 0) return 'now';
  const totalSeconds = Math.ceil(ms / 1000);
  const hours = Math.floor(totalSeconds / 3600);
  const minutes = Math.floor((totalSeconds % 3600) / 60);
  const seconds = totalSeconds % 60;

  if (hours > 0) {
    return `${hours}h ${minutes}m`;
  }
  if (minutes > 0) {
    return `${minutes}m ${seconds}s`;
  }
  return `${seconds}s`;
}
